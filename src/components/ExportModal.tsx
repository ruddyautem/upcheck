'use client';

import React from 'react';
import { getRepositoryTarget, repositoryTargetUrl } from '@/lib/repositoryTarget';
import { RepoAnalysisResult } from '@/types';
import { X, Copy, Download, FileText } from 'lucide-react';
import { toast } from 'sonner';
import { useDialog } from '@/hooks/useDialog';
import { useId } from 'react';
import { useAppSettings } from '@/lib/settingsContext';

interface ExportModalProps {
  result: RepoAnalysisResult;
  onClose: () => void;
}

export function ExportModal({ result, onClose }: ExportModalProps) {
  const { t } = useAppSettings();
  const dialogRef = useDialog(onClose);
  const titleId = useId();

  // Generate Markdown report
  const generateMarkdownReport = () => {
    let md = `# 🛡️ Upcheck Dependency Audit Report\n\n`;
    md += `**Repository**: [${result.repoInfo.fullName}](${repositoryTargetUrl(getRepositoryTarget(result.repoInfo))})\n`;
    const target = getRepositoryTarget(result.repoInfo);
    md += `**Branch**: ${target.branch || "default"} · **Manifest**: ${target.path || "package.json"}\n`;
    md += `**Audit Date**: ${new Date(result.analyzedAt).toUTCString()}\n`;
    if (result.isIncomplete) md += '**Incomplete scan**: Some versions or advisory severities could not be verified.\n';
    if (result.isEstimated) md += '**Estimated versions**: Manifest ranges do not identify installed versions. Audit the lockfile separately.\n';
    md += `**Health Score**: **${result.healthScore.score} / 100** (Grade: **${result.healthScore.grade}** - ${result.healthScore.label})\n`;
    md += `**Total Dependencies**: ${result.totalPackages} (${result.dependenciesCount} prod, ${result.devDependenciesCount} dev)\n\n`;

    md += `## 📊 Executive Summary\n`;
    md += `- 🔴 **Packages with high/critical advisories**: ${result.summaryCounts.critical}\n`;
    md += `- 🟠 **Packages with other security advisories**: ${result.summaryCounts.security}\n`;
    md += `- ⚠️ **Deprecated Packages**: ${result.summaryCounts.deprecated}\n`;
    md += `- 🟣 **Major Updates (Migration Review)**: ${result.packages.filter((pkg) => pkg.hasBreakingChanges).length}\n`;
    md += `- 🔵 **Minor Updates**: ${result.summaryCounts.minor}\n`;
    md += `- ⚪ **Patch Updates**: ${result.summaryCounts.patch}\n`;
    md += `- 🟢 **Up to Date**: ${result.summaryCounts.up_to_date}\n\n`;

    md += `## 📦 Detailed Packages Breakdown\n\n`;
    md += `| Package | Current | Latest | Category | Advisories / Deprecations |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- |\n`;

    result.packages.forEach((pkg) => {
      let notes = '-';
      if (pkg.deprecatedReason) {
        notes = `⚠️ DEPRECATED: ${pkg.deprecatedReason.replace(/\n/g, ' ')}`;
      } else if (pkg.advisories.length > 0) {
        notes = pkg.advisories.map((a) => `${a.id} (${a.severity})`).join(', ');
      }
      md += `| \`${pkg.name}\` | \`${pkg.currentVersion}\` | \`${pkg.latestVersion}\` | **${pkg.category.toUpperCase()}** | ${notes} |\n`;
    });

    md += `\n---\n*Generated by Upcheck - GitHub Dependency Inspector*\n`;
    return md;
  };

  const markdownContent = generateMarkdownReport();

  const handleCopyMarkdown = async () => {
    try {
      await navigator.clipboard.writeText(markdownContent);
      toast.success(t('export.copied'), { className: 'upcheck-toast--blue' });
    } catch { toast.error(t('scripts.copy_failed')); }
  };

  const handleDownloadMarkdown = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `upcheck-report-${result.repoInfo.repo}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJson = () => {
    const blob = new Blob([JSON.stringify(result, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `upcheck-audit-${result.repoInfo.repo}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in duration-200">
      <div ref={dialogRef} role="dialog" aria-modal="true" aria-labelledby={titleId} tabIndex={-1}
        className="relative w-full max-w-2xl bg-slate-900 border border-slate-800 rounded-3xl shadow-2xl overflow-hidden max-h-[90vh] flex flex-col"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="p-6 border-b border-slate-800 flex items-center justify-between bg-slate-950/50">
          <div className="flex items-center gap-3">
            <div className="p-2.5 rounded-xl bg-cyan-600/20 text-cyan-400 border border-cyan-500/30">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 id={titleId} className="text-lg font-bold text-white">{t('export.title')}</h3>
              <p className="text-xs text-slate-400">{t('export.subtitle')}</p>
            </div>
          </div>

          <button
            aria-label={t('token.cancel_btn')}
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="p-6 space-y-4 overflow-y-auto">
          <div className="flex items-center justify-between flex-wrap gap-2">
            <span className="text-xs font-semibold text-slate-300">{t('export.preview_title')}</span>
            <div className="flex items-center gap-2">
              <button
                onClick={handleCopyMarkdown}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-mono transition-colors cursor-pointer"
              >
                <Copy className="w-3.5 h-3.5" />
                <span>{t('export.copy_md')}</span>
              </button>
              <button
                onClick={handleDownloadMarkdown}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-500 text-white text-xs font-medium transition-colors cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>{t('export.download_md')}</span>
              </button>
              <button
                onClick={handleDownloadJson}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium border border-slate-700/60 transition-colors cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>{t('export.download_json')}</span>
              </button>
            </div>
          </div>

          <pre className="p-4 bg-slate-950 rounded-2xl border border-slate-800 text-xs font-mono text-slate-300 max-h-96 overflow-y-auto whitespace-pre-wrap">
            {markdownContent}
          </pre>
        </div>
      </div>
    </div>
  );
}
